            $categoryName   = $data['اسم_الفئة'] ?? null;
            $categoryNumber = $data['رقم_الفئة'] ?? null;

            if (! $jobName) {
                continue;
            }

            // try find category by name, with fallback to flexible matching
            $categoryId = null;
            if ($categoryName) {
                $categoryName = trim($categoryName);
                $cat          = Category::where('name', $categoryName)->first();
                if (! $cat) {
                    $cat = Category::where('name', 'like', "%{$categoryName}%")->first();
                }
                if ($cat) {
                    $categoryId = $cat->id;
                }
            }

            // fallback: numeric category id
            if (! $categoryId && is_numeric($categoryNumber)) {
                $maybe = Category::find((int) $categoryNumber);
                if ($maybe) {
                    $categoryId = $maybe->id;
                }
            }

            // create or update by name, and always set a valid category_id
            Job::updateOrCreate(
                ['name' => $jobName],
                ['category_id' => $categoryId ?: $defaultCategory->id]
